import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE,headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference'});
try{
 const start=new Date('2026-10-20T12:00:00Z');await page.clock.install({time:start});await page.clock.pauseAt(new Date(start.getTime()+1000));
 await page.goto('http://127.0.0.1:3000/');
 const programs=page.getByRole('region',{name:'Nuestros programas',exact:true});
 const testimonials=page.getByRole('region',{name:'Testimonios de estudiantes',exact:true});
 await programs.getByRole('button',{name:'Pausar carrusel',exact:true}).waitFor();
 assert.equal(await programs.locator('img').getAttribute('src'),'/images/english.png');
 assert.equal(await page.locator('.programs-orange').count(),0);
 assert.equal(await page.locator('.programs-section').evaluate(e=>getComputedStyle(e).backgroundColor),'rgba(0, 0, 0, 0)');
 assert.equal(await testimonials.locator('.carousel-arrows button').last().isDisabled(),true);
 assert.equal(await testimonials.getByRole('button',{name:'Pausar carrusel',exact:true}).count(),0);
 assert.equal(await page.locator('.sample-label,.sample-testimonial').count(),0);
 await page.clock.runFor(7999);assert.match(await programs.innerText(),/Aprende inglés/);
 await page.clock.runFor(1);await programs.getByRole('heading',{name:'Aprende español',exact:true}).waitFor();
 assert.equal(await programs.locator('img').getAttribute('src'),'/images/spanish.png');
 await page.clock.runFor(8000);await programs.getByRole('heading',{name:'Preparación IELTS / TOEFL',exact:true}).waitFor();
 await page.clock.runFor(8000);await programs.getByRole('heading',{name:'Aprende inglés',exact:true}).waitFor();
 await programs.hover();await page.clock.runFor(16000);assert.match(await programs.innerText(),/Aprende inglés/);
 await page.mouse.move(0,0);await page.clock.runFor(8000);await programs.getByRole('heading',{name:'Aprende español',exact:true}).waitFor();
 await programs.getByRole('button',{name:'Pausar carrusel',exact:true}).click();await page.locator('h1').click();await page.clock.runFor(16000);assert.match(await programs.innerText(),/Aprende español/);
 await testimonials.locator('summary').click();await page.locator('h1').click();await page.clock.runFor(16000);
 assert.match(await testimonials.innerText(),/Samantha Fornaris/);assert.match(await testimonials.locator('details[open]').innerText(),/le apasiona de verdad enseñar/);
 await page.emulateMedia({reducedMotion:'reduce'});await page.clock.runFor(0);
 const before=await programs.locator('.carousel-progress strong').innerText();await page.clock.runFor(16000);assert.equal(await programs.locator('.carousel-progress strong').innerText(),before);
 console.log('PASS: light program background, supplied images, 8-second autoplay, only Samantha testimonial, pauses and reduced motion.');
}finally{await browser.close()}
